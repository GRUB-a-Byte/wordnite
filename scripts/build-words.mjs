#!/usr/bin/env node
/**
 * Generates lib/words/answers.ts and lib/words/valid.ts from SCOWL
 * (Spell Checker Oriented Word Lists, http://wordlist.aspell.net/, Copyright 2000-2018 Kevin Atkinson,
 * permissive licence — see lib/words/LICENSE-SCOWL.txt).
 *
 * Usage:
 *   1. Download scowl-2020.12.07.tar.gz from https://sourceforge.net/projects/wordlist/files/SCOWL/
 *   2. Extract it anywhere (outside this repo).
 *   3. node scripts/build-words.mjs /path/to/scowl-2020.12.07/final
 *
 * Answer list (SRS §8.7): SCOWL size <= 35, plurals / 3rd-person "-s" forms and simple "-ed" past
 * tenses removed, offensive words removed.
 * Valid-guess list: SCOWL size <= 80 (size <= 70 only yields ~6.5k five-letter words; <= 80 yields
 * the ~11k the SRS asked for) plus every answer.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const finalDir = process.argv[2];
if (!finalDir || !existsSync(finalDir)) {
  console.error('Usage: node scripts/build-words.mjs <path to SCOWL final/ directory>');
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const blocklist = new Set(
  readFileSync(join(root, 'lib/words/blocklist.txt'), 'utf8')
    .split(/\r?\n/)
    .map((l) => l.trim().toLowerCase())
    .filter((l) => l && !l.startsWith('#')),
);

const ANSWER_LEVELS = [10, 20, 35];
const VALID_LEVELS = [10, 20, 35, 40, 50, 55, 60, 70, 80];
const ANSWER_SPELLINGS = ['english', 'american'];
const VALID_SPELLINGS = ['english', 'american', 'british'];

function readList(name) {
  const file = join(finalDir, name);
  if (!existsSync(file)) return [];
  // SCOWL lists are ISO-8859-1; latin1 decoding keeps ASCII words intact and we filter to a-z anyway.
  return readFileSync(file, 'latin1').split(/\r?\n/);
}

function collect(spellings, levels) {
  const out = new Set();
  for (const spelling of spellings) {
    for (const level of levels) {
      for (const w of readList(`${spelling}-words.${level}`)) {
        if (/^[a-z]{5}$/.test(w)) out.add(w);
      }
    }
  }
  return out;
}

// Every SCOWL word of any length (size <= 80) — used to detect inflected forms such as "cakes" -> "cake".
const allWords = new Set();
for (const spelling of VALID_SPELLINGS) {
  for (const level of VALID_LEVELS) {
    for (const w of readList(`${spelling}-words.${level}`)) if (/^[a-z]+$/.test(w)) allWords.add(w);
  }
}

function isInflection(w) {
  if (w.endsWith('s') && !w.endsWith('ss')) {
    if (allWords.has(w.slice(0, -1))) return true; // cakes -> cake
    if (w.endsWith('es') && allWords.has(w.slice(0, -2))) return true; // boxes -> box
    if (w.endsWith('ies') && allWords.has(w.slice(0, -3) + 'y')) return true; // flies -> fly
  }
  if (w.endsWith('ed')) {
    if (allWords.has(w.slice(0, -1))) return true; // liked -> like
    if (allWords.has(w.slice(0, -2))) return true; // aimed -> aim
    if (w.endsWith('ied') && allWords.has(w.slice(0, -3) + 'y')) return true; // tried -> try
    if (w.length >= 5 && w[w.length - 3] === w[w.length - 4] && allWords.has(w.slice(0, -3))) return true; // begged-style
  }
  return false;
}

const answers = [...collect(ANSWER_SPELLINGS, ANSWER_LEVELS)]
  .filter((w) => !isInflection(w))
  .filter((w) => !blocklist.has(w))
  .sort();

const valid = new Set(collect(VALID_SPELLINGS, VALID_LEVELS));
for (const a of answers) valid.add(a);
const validSorted = [...valid].sort();

function emit(file, constName, words, comment) {
  const body = words.map((w) => w.toUpperCase()).join('');
  const src =
    `// AUTO-GENERATED by scripts/build-words.mjs from SCOWL (see lib/words/LICENSE-SCOWL.txt). Do not edit.\n` +
    `// ${comment}\n` +
    `// ${words.length} words, packed as one string of consecutive 5-letter upper-case words.\n` +
    `export const ${constName} = '${body}';\n`;
  writeFileSync(join(root, file), src);
}

emit('lib/words/answers.ts', 'PACKED_ANSWERS', answers, 'Secret-word answer list (SCOWL size <= 35, curated).');
emit('lib/words/valid.ts', 'PACKED_VALID', validSorted, 'Valid-guess list (SCOWL size <= 80 + answers).');
console.log(`answers: ${answers.length}, valid guesses: ${validSorted.length}`);
